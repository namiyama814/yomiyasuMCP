"""Verify the pinned snapshot and embed text lists for the Python WASM filesystem."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)

meta = json.loads((ROOT / 'upstream.json').read_text())
base = ROOT / 'checker/src/vendor'
for name, digest in meta['files'].items():
    if hashlib.sha256((base / name).read_bytes()).hexdigest() != digest:
        raise SystemExit(f'Upstream snapshot mismatch: {name}')
refs = {str(p.relative_to(base)): p.read_text() for p in sorted((base / 'references').rglob('*')) if p.is_file()}
skill = (base / 'SKILL.md').read_text()
write_if_changed(ROOT / 'src/generated.ts', '// Generated by scripts/prepare_data.py\nexport const upstream = ' + json.dumps({k:v for k,v in meta.items() if k != 'files'}, ensure_ascii=False) + ' as const;\nexport const skill = ' + json.dumps(skill, ensure_ascii=False) + ';\nexport const references: Record<string,string> = ' + json.dumps(refs, ensure_ascii=False) + ';\n')
# Python Workers bundles Python modules; embed reference data rather than relying on non-Python files.
write_if_changed(ROOT / 'checker/src/vendor_data.py', '# Generated by scripts/prepare_data.py\nUPSTREAM = ' + repr({k:v for k,v in meta.items() if k != 'files'}) + '\nREFERENCES = ' + repr(refs) + '\n')
print(f'Verified {len(meta["files"])} upstream files; embedded {len(refs)} references')
